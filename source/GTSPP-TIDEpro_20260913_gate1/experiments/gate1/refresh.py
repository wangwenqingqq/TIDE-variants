"""Preserve compiler-only v1, rebuild owner instrumentation, regenerate/hash-compare every oracle."""
import argparse
import json
from pathlib import Path
import subprocess
import time

from build import ROOT, digest, inputs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--revision", choices=("v2", "v3", "v4"), default="v2")
    args = parser.parse_args()
    build = ROOT / "build"
    old = json.loads((build / "CPU_READY.json").read_text())
    supplement = json.loads((build / "CPU_GATE1M.json").read_text())
    data, gate = Path(old["input"]), Path(supplement["input"])
    if inputs(data) != old["input_hashes"] or inputs(gate) != supplement["input_hashes"]:
        raise RuntimeError("input changed")
    scratch = ROOT / ("raw_data/oracle_recheck_" + args.revision)
    scratch.mkdir(exist_ok=False)
    binary = build / ("replay_" + args.revision)
    if binary.exists():
        raise RuntimeError("refusing existing v2 binary")
    command = ["/usr/local/cuda-13.1/bin/nvcc", "-std=c++17", "-O3", "-arch=sm_120", "-lineinfo",
               "-Xcompiler=-O3,-march=native,-fopenmp,-pthread", "--ptxas-options=-v",
               "experiments/gate1/replay.cu", "-o", str(binary)]
    commands = []

    def invoke(cmd, label):
        start = time.monotonic()
        proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=600)
        log = build / ("refresh_" + args.revision + "_" + label + ".log")
        log.write_text(proc.stdout + proc.stderr)
        print(proc.stdout + proc.stderr, flush=True)
        commands.append({"argv": cmd, "returncode": proc.returncode, "wall_s": time.monotonic() - start,
                         "log": str(log.relative_to(ROOT)), "log_sha256": digest(log)})
        if proc.returncode:
            raise RuntimeError("refresh failed, evidence retained")

    invoke(command, "compile")
    for label, origin, hashes, prefix in (("fixture", data / "fixture", old["oracle_hashes"], "fixture/"),
                                          ("large", data, old["oracle_hashes"], ""),
                                          ("million", gate, supplement["oracle_hashes"], "")):
        target = scratch / label
        target.mkdir()
        for name in [f"run{i}.bin" for i in range(7)] + ["queries.bin"]:
            (target / name).symlink_to(origin / name)
        invoke([str(binary), "--mode", "oracle", "--root", str(target)], label)
        paths = sorted(target.glob("oracle/*.bin"))
        if len(paths) != 896 or any(digest(p) != hashes[prefix + "oracle/" + p.name] for p in paths):
            raise RuntimeError("regenerated complete oracles differ")
    for name in ("CPU_READY.json", "CPU_GATE1M.json", "replay"):
        previous = build / (name + ".pre_" + args.revision)
        if previous.exists():
            raise RuntimeError("compiler v1 archive already exists")
        (build / name).rename(previous)
    binary.rename(build / "replay")
    old["sources"] = {p: digest(ROOT / p) for p in old["sources"]}
    old["sources"]["experiments/gate1/refresh.py"] = digest(Path(__file__))
    old["binary_sha256"] = digest(build / "replay")
    old["commands"].extend(commands)
    old["refresh_scope"] = "revision " + args.revision + "; all 2688 oracle vectors regenerated byte-identically; preceding receipts and binary archived"
    old["completed_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    supplement["binary_sha256"] = old["binary_sha256"]
    supplement["regenerated_and_hash_compared"] = True
    (build / "CPU_READY.json").write_text(json.dumps(old, indent=2) + "\n")
    (build / "CPU_GATE1M.json").write_text(json.dumps(supplement, indent=2) + "\n")
    print("CPU_REFRESH_PASS 2688 vectors identical; initial compiler artifacts preserved", flush=True)


if __name__ == "__main__":
    main()
